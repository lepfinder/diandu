def take_name(rest: str) -> str:
    for size in (3, 2):
        name = rest[:size]
        if not re.fullmatch(r"[\u4e00-\u9fff]{2,3}", name):
            continue
        tail = rest[size:]
        if tail == "" or re.match(r"[天地][\u4e00-\u9fff]星", tail):
            return name
    if re.match(r"[\u4e00-\u9fff]{2}", rest) and (len(rest) == 2 or rest[2] not in "天地"):
        return rest[:2]
    raise SystemExit(f"名单里的姓名接不下来：{rest[:12]}")


def roster(chapter_text: str) -> list[tuple[str, str, str]]:
    start = chapter_text.find("天魁星")
    end = chapter_text.find("段景住")
    if start < 0 or end < 0:
        raise SystemExit("第七十一回里没有找到石碣名单")
    block = chapter_text[start : end + len("段景住")]
    marks = list(re.finditer(r"([天地][\u4e00-\u9fff]星)「([^」]+)」", block))
    found: list[tuple[str, str, str]] = []
    for mark in marks:
        found.append((mark.group(1), mark.group(2), take_name(block[mark.end() :])))
    if len(found) != 108:
        raise SystemExit(f"石碣名单解析出 {len(found)} 人，不是 108")
    return found


def span(chapters: list[dict], names: list[str]) -> tuple[int, int]:
    first = None
    last = None
    for chapter in chapters:
        blob = chapter["title"] + "".join(chapter["paras"])
        if any(name and name in blob for name in names):
            if first is None:
                first = chapter["n"]
            last = chapter["n"]
    if first is None or last is None:
        raise SystemExit(f"全书找不到：{names}")
    return first, last


